-- AdSentry V1 Schema Migration
-- Designed for PostgreSQL 15+ and compatible with H2 (PostgreSQL compatibility mode)

CREATE TABLE import_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    platform VARCHAR(50) NOT NULL,
    original_filename VARCHAR(255) NOT NULL,
    import_timestamp TIMESTAMP WITH TIME ZONE NOT NULL,
    reporting_start_date DATE,
    reporting_end_date DATE,
    status VARCHAR(30) NOT NULL,
    currency VARCHAR(10) NOT NULL,
    total_rows INT NOT NULL DEFAULT 0,
    accepted_rows INT NOT NULL DEFAULT 0,
    rejected_rows INT NOT NULL DEFAULT 0,
    duplicate_rows INT NOT NULL DEFAULT 0,
    updated_rows INT NOT NULL DEFAULT 0,
    column_mapping_json TEXT,
    validation_summary TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE imported_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    identity_key VARCHAR(128) NOT NULL,
    platform VARCHAR(50) NOT NULL,
    campaign_id VARCHAR(100),
    campaign_name VARCHAR(255) NOT NULL,
    campaign_name_normalized VARCHAR(255) NOT NULL,
    identity_confidence VARCHAR(20) NOT NULL,
    reporting_date DATE NOT NULL,
    spend NUMERIC(15, 2) NOT NULL,
    currency VARCHAR(10) NOT NULL,
    impressions BIGINT,
    clicks BIGINT,
    conversions NUMERIC(12, 2),
    conversion_definition VARCHAR(50) NOT NULL DEFAULT 'UNSPECIFIED',
    dimensions_json TEXT,
    source_row_number INT NOT NULL,
    imported_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_imported_records_batch FOREIGN KEY (batch_id) REFERENCES import_batches (id) ON DELETE CASCADE
);

CREATE INDEX idx_imported_records_identity ON imported_records (identity_key, imported_at DESC);
CREATE INDEX idx_imported_records_batch ON imported_records (batch_id);
CREATE INDEX idx_imported_records_date ON imported_records (reporting_date);
CREATE INDEX idx_imported_records_platform ON imported_records (platform);

CREATE TABLE import_row_errors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    source_row_number INT NOT NULL,
    field_name VARCHAR(100),
    error_code VARCHAR(50) NOT NULL,
    error_message TEXT NOT NULL,
    CONSTRAINT fk_import_row_errors_batch FOREIGN KEY (batch_id) REFERENCES import_batches (id) ON DELETE CASCADE
);

CREATE INDEX idx_row_errors_batch ON import_row_errors (batch_id);

CREATE TABLE app_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    setting_key VARCHAR(50) NOT NULL UNIQUE,
    setting_value VARCHAR(255) NOT NULL,
    description VARCHAR(255),
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE recommendations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fingerprint VARCHAR(128) NOT NULL UNIQUE,
    rule_identifier VARCHAR(50) NOT NULL,
    platform VARCHAR(50) NOT NULL,
    campaign_name VARCHAR(255) NOT NULL,
    campaign_identity_key VARCHAR(128) NOT NULL,
    identity_reliability VARCHAR(20) NOT NULL,
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    priority VARCHAR(20) NOT NULL,
    title VARCHAR(255) NOT NULL,
    explanation TEXT NOT NULL,
    suggested_action TEXT NOT NULL,
    supporting_metrics_json TEXT NOT NULL,
    trigger_condition TEXT NOT NULL,
    thresholds_used_json TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'NEW',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_recommendations_status ON recommendations (status);
CREATE INDEX idx_recommendations_rule ON recommendations (rule_identifier);
CREATE INDEX idx_recommendations_period ON recommendations (period_start, period_end);

-- Effective Records View
-- Evaluates the winning version for each identity key across COMPLETED batches by newest import timestamp.
-- Foreign key ON DELETE CASCADE automatically restores the next newest version when a winning batch is deleted.
CREATE VIEW effective_records_view AS
WITH ranked_records AS (
    SELECT r.id,
           r.batch_id,
           r.identity_key,
           r.platform,
           r.campaign_id,
           r.campaign_name,
           r.campaign_name_normalized,
           r.identity_confidence,
           r.reporting_date,
           r.spend,
           r.currency,
           r.impressions,
           r.clicks,
           r.conversions,
           r.conversion_definition,
           r.dimensions_json,
           r.source_row_number,
           r.imported_at,
           ROW_NUMBER() OVER (
               PARTITION BY r.identity_key 
               ORDER BY b.import_timestamp DESC, r.id DESC
           ) AS row_rank
    FROM imported_records r
    JOIN import_batches b ON r.batch_id = b.id
    WHERE b.status = 'COMPLETED'
)
SELECT id, batch_id, identity_key, platform, campaign_id, campaign_name,
       campaign_name_normalized, identity_confidence, reporting_date, spend,
       currency, impressions, clicks, conversions, conversion_definition,
       dimensions_json, source_row_number, imported_at
FROM ranked_records
WHERE row_rank = 1;

